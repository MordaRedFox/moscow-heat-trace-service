package ru.moscow.heat.trace.dto;

/**
 * Тип кандидата на присоединение к тепловой сети.
 * Согласно разделу 3.2 ТП ЛЦТ-2026:
 * - EXISTING_CHAMBER: присоединение к существующей тепловой камере (в радиусе 10 м)
 * - NEW_CHAMBER: строительство новой камеры на существующей теплосети
 */
public enum TieInType {
    /** Присоединение к существующей тепловой камере */
    EXISTING_CHAMBER,

    /** Строительство новой тепловой камеры в точке врезки на сети */
    NEW_CHAMBER
}
