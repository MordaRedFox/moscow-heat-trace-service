package ru.moscow.heat.trace.model;

/**
 * Тип узла маршрута новой тепловой сети.
 * <p>
 * Итерация 5, п.3 "Пакет trace/model".
 */
public enum RouteNodeType {

    /** Точка подключения перспективного ОКС — начало маршрута. */
    OKS_POINT,

    /** Существующая тепловая камера, выбранная точкой врезки. */
    EXISTING_CHAMBER,

    /** Новая тепловая камера, создаваемая в точке врезки или разветвления. */
    NEW_CHAMBER,

    /** Служебная точка смены ДУ / способа прокладки / границы спецзоны. */
    TECHNICAL_NODE,

    /** Угловая точка маршрута (поворот на прямом участке, не имеющий особого статуса). */
    CORNER
}
